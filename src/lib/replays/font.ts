export interface TextStyle {
  color: string;
  /** Whole pixels per font pixel */
  scale?: number;
  /** Doubled sideways: the scoreboard face */
  bold?: boolean;
}

/** Pixels from one character's left edge to the next. */
export function advance(bold: boolean): number {
  return GLYPH_W + (bold ? 2 : 1);
}

export function textWidth(text: string, style: Pick<TextStyle, 'scale' | 'bold'> = {}): number {
  const scale = style.scale ?? 1;
  const bold = style.bold ?? true;
  if (text.length === 0) return 0;
  return (text.length * advance(bold) - 1) * scale;
}

/** Draw text with its top left at (x, y); returns its width. */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, style: TextStyle): number {
  const scale = style.scale ?? 1;
  const bold = style.bold ?? true;
  ctx.fillStyle = style.color;
  let left = Math.round(x);
  const top = Math.round(y);
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS[' ']!;
    glyph.forEach((row, r) => {
      for (let c = 0; c < row.length; c++) {
        if (row[c] !== '#') continue;
        ctx.fillRect(left + c * scale, top + r * scale, (bold ? 2 : 1) * scale, scale);
      }
    });
    left += advance(bold) * scale;
  }
  return textWidth(text, style);
}
